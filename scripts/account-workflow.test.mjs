import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes,randomUUID}from'node:crypto';
const base=process.env.TRACKER_TEST_URL??'http://localhost:5080';
function client(){let cookie='';return async(method,path,body,status=200)=>{
 const response=await fetch(base+path,{method,headers:{...(cookie?{Cookie:cookie}:{}),...(body?{'Content-Type':'application/json'}:{})},...(body?{body:JSON.stringify(body)}:{})});
 const cookies=response.headers.getSetCookie();if(cookies.length)cookie=cookies.map(value=>value.split(';')[0]).join('; ');
 const raw=await response.text();assert.equal(response.status,status,`${method} ${path}: ${raw.slice(0,300)}`);
 return raw&&response.headers.get('Content-Type')?.includes('json')?JSON.parse(raw):raw;
};}
test('registered accounts have isolated tracking, targets, notifications, settings, plans and chat',{timeout:120000},async()=>{
 const anonymous=client(),a=client(),b=client();
 await anonymous('GET','/api/products',null,401);
 const password=randomBytes(20).toString('base64url'),email=`test-${randomUUID()}@example.com`;
 await a('POST','/api/auth/register',{email,password,displayName:'Account A'});
 await b('POST','/api/auth/register',{email:`test-${randomUUID()}@example.com`,password,displayName:'Account B'});
 await anonymous('POST','/api/auth/login',{email,password:'wrong-password'},401);
 await anonymous('POST','/api/auth/register',{email:email.toUpperCase(),password,displayName:'Duplicate'},409);
 const beforeA=await a('GET','/api/products'),beforeB=await b('GET','/api/products');assert.ok(beforeA.length>0);
 const product=beforeA[0],id=product.ozonProductId;
 await a('PUT',`/api/products/${id}/preferences`,{isFavorite:true,targetPrice:Math.round(product.price*.9*100)/100});
 assert.equal((await a('GET','/api/notifications')).unreadCount,0);
 await a('POST','/api/demo/scenario',{scenario:'sale',ozonProductId:id});
 let inbox=await a('GET','/api/notifications');assert.equal(inbox.unreadCount,1);assert.ok(inbox.items[0].price<=inbox.items[0].targetPrice);
 await a('POST','/api/demo/scenario',{scenario:'sale',ozonProductId:id});assert.equal((await a('GET','/api/notifications')).unreadCount,1,'Repeated below-target prices must not spam alerts');
 assert.deepEqual(await b('GET','/api/products'),beforeB,'Another account must not see generated prices or preferences');
 assert.equal((await b('GET','/api/notifications')).unreadCount,0);
 await b('POST',`/api/notifications/${inbox.items[0].id}/read`,null,404);
 await a('POST',`/api/notifications/${inbox.items[0].id}/read`,null,204);assert.equal((await a('GET','/api/notifications')).unreadCount,0);
 await a('POST','/api/demo/scenario',{scenario:'outOfStock',ozonProductId:id});assert.equal((await a('GET',`/api/products/${id}`)).stocks,0);
 await a('POST','/api/demo/scenario',{scenario:'restock',ozonProductId:id});assert.equal((await a('GET',`/api/products/${id}`)).stocks,50);
 await a('PUT','/api/profile/settings',{refreshMinutes:15,notificationsEnabled:false,compactTable:true});
 assert.equal((await b('GET','/api/profile')).refreshMinutes,60);assert.equal((await b('GET','/api/profile')).notificationsEnabled,true);assert.equal((await b('GET','/api/profile')).compactTable,false);
 const current=await a('GET',`/api/products/${id}`);
 const alertsBefore=(await a('GET','/api/notifications')).items.length;
 await a('PUT',`/api/products/${id}/preferences`,{isFavorite:true,targetPrice:current.price*2});
 await a('POST','/api/demo/scenario',{scenario:'sale',ozonProductId:id});
 assert.equal((await a('GET','/api/notifications')).items.length,alertsBefore,'Disabled notifications must not create new alerts');
 assert.equal((await a('GET','/api/profile')).compactTable,true);
 await a('PUT','/api/profile/settings',{refreshMinutes:15,notificationsEnabled:true,compactTable:true});
 await a('POST','/api/demo/scenario',{scenario:'restock',ozonProductId:id});
 assert.equal((await a('GET','/api/notifications')).items.length,alertsBefore+1,'Enabled rule should evaluate on the next snapshot');
 await a('PUT','/api/profile/subscription',{subscription:'Pro'});await a('POST','/api/chat',{text:'Покажи сводку'});
 await b('GET','/api/chat',null,403);await b('GET','/api/products/export',null,403);
 await b('PUT','/api/profile/subscription',{subscription:'Pro'});assert.deepEqual(await b('GET','/api/chat'),[]);
 const history=(await a('GET',`/api/products/${id}`)).history;
 await a('DELETE',`/api/products/${id}`,null,204);assert.equal((await b('GET','/api/products')).length,beforeB.length);
 await a('POST','/api/products',{value:String(id)},201);assert.deepEqual((await a('GET',`/api/products/${id}`)).history,history);
 await a('POST','/api/auth/logout',null,204);await a('GET','/api/profile',null,401);
 await a('POST','/api/auth/login',{email,password});assert.equal((await a('GET',`/api/products/${id}`)).isFavorite,true);
 await a('POST','/api/auth/logout',null,204);await b('POST','/api/auth/logout',null,204);
});
